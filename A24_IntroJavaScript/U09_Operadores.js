// Uso de los operadores eb JavaScript
// -----------------------------------
//  + suma          - Resta             * Producto
//  / Division      %  Modulo (Residuo) ** Exponente
//  ++ Incremento   -- Decremento

let a = 3, b = 2;
let z = a + b;

console.log("Resultado de la suma: " + z);

z = a - b;
console.log("Resultado de la resta: " + z);

z = a * b;
console.log("Resultado de la multi: " + z);

z = a /b;
console.log("Resultado de la división: " + z);

z = a % b;
console.log("Resultado del modulo: " + z);

z = a ** b;
console.log("Resultado de operador exponente: " + z);
