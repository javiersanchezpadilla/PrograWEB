// Operadores de asignación (=)
// nos permite asignar un valor

let a = 1;

// OPERADORES DE ASIGNACIÓN COMPUESTOS
// -----------------------------------

a += 3;     // equivale a a = a + 3
console.log(a);

a -= 2;     // a = a -2 = 4 - 2 = 2
console.log(a);

// El resto de los oeperadores compuestos son
// a += 10    equivale a  a = a + 10
// a -= 10    equivale a  a = a - 10
// a *= 10    equivale a  a = a * 10
// a /= 10    equivale a  a = a / 10
// a %= 10    equivale a  a = a % 10
// a **= 10    equivale a  a = a ** 10

a **= 3;
console.log(a);     // a **= 3 equivale a a=a**3 = a*a*a =  2*2*2 = 8
