/* TEMPLATE STRING

Con las comillas tradicionales, al intentabas presionar la tecla Enter para 
escribir un texto largo en varias líneas, JavaScript te marcaba un error.
Con los template strings, podmeos escribir el texto en las líneas requeridas
tal cual aparecerá en pantalla:

Las comillas invertidas ` y el comodín ${variable} facilitan las tareas, 
eliminan los molestos signos de suma y hacen que el código sea mas sencillo 
de leer.
*/

const carta_bienvenida = `
  Hola, estimado estudiante:
  
  Te damos la más cordial bienvenida al curso de programación.
  
  ¡Mucho éxito!
`;

console.log(carta_bienvenida);

